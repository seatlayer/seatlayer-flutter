// Writes lib/src/picker/picker_money_table.g.dart: how each language of the
// picker writes amounts, from the number data of the Node that runs this.
//
//   node tool/gen_money_table.mjs
//
// The drawn map writes amounts with the browser's own number formats; this is
// the same data, so the chrome beside it writes them alike.
import { readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const picker = join(
  dirname(fileURLToPath(import.meta.url)),
  '../lib/src/picker',
);
const tags = readdirSync(picker)
  .map((name) => /^picker_strings\.(.+)\.g\.dart$/.exec(name)?.[1])
  .filter((tag) => tag !== undefined)
  .map((tag) =>
    tag.replace(/_(\w)(\w+)/, (_, a, b) => `-${a.toUpperCase()}${b}`),
  )
  .sort();
const currencies = Intl.supportedValuesOf('currency');

const parts = (tag, currency, amount, digits) =>
  new Intl.NumberFormat(tag, {
    style: 'currency',
    currency,
    minimumFractionDigits: digits,
    maximumFractionDigits: digits,
    // The map writes Arabic amounts with 0 to 9.
    ...(tag === 'ar' ? { numberingSystem: 'latn' } : {}),
  }).formatToParts(amount);

const quote = (text) =>
  `'${[...text]
    .map((char) => {
      const code = char.codePointAt(0);
      if (char === "'" || char === '$' || char === '\\') return `\\${char}`;
      // Marks, spaces and direction marks nobody can see in an editor.
      return code < 0x20 || (code >= 0x7f && code <= 0xa0) ||
        (code >= 0x2000 && code <= 0x206f) || code === 0x202f
        ? `\\u{${code.toString(16).toUpperCase()}}`
        : char;
    })
    .join('')}'`;

const of = (list, type) => list.find((part) => part.type === type)?.value ?? '';

function rule(tag) {
  const long = parts(tag, 'EUR', 1234567.5, 2);
  const at = long.findIndex((part) => part.type === 'currency');
  const first = long.findIndex((part) => part.type === 'integer');
  const last = long.findLastIndex((part) => part.type === 'fraction');
  const markFirst = at < first;
  const join = (list) => list.map((part) => part.value).join('');
  const fields = {
    markFirst,
    lead: join(long.slice(0, markFirst ? at : first)),
    gap: join(markFirst ? long.slice(at + 1, first) : long.slice(last + 1, at)),
    group: of(long, 'group'),
    decimal: of(long, 'decimal'),
    groupsFromFive:
      of(parts(tag, 'EUR', 1234, 0), 'group') === '',
    lakhs: join(parts(tag, 'EUR', 1234567, 0)).includes('12,34,567'),
    digits: new Intl.NumberFormat(tag, {
      useGrouping: false,
      ...(tag === 'ar' ? { numberingSystem: 'latn' } : {}),
    }).format(9876543210).split('').reverse().join(''),
  };
  const marks = {};
  for (const code of currencies) {
    const list = parts(tag, code, 1, 0);
    const text = list.map((part) => part.value).join('');
    const one = of(list, 'integer');
    // The whole mark, direction marks of its own included.
    const mark = fields.markFirst
      ? of(list, 'currency')
      : text.slice(text.indexOf(one) + one.length + fields.gap.length);
    if (mark !== code) marks[code] = mark;
  }
  return { fields, marks };
}

const lines = [
  '// GENERATED by tool/gen_money_table.mjs. Do not edit.',
  '//',
  `// Number data: Unicode CLDR by way of ICU ${process.versions.icu}.`,
  '// ignore_for_file: lines_longer_than_80_chars',
  '',
  "import 'picker_money.dart';",
  '',
  '/// How each language the picker speaks writes amounts.',
  'const Map<String, PickerMoneyRule> pickerMoneyRules = <String, PickerMoneyRule>{',
];
for (const tag of tags) {
  const { fields, marks } = rule(tag);
  lines.push(`  '${tag}': PickerMoneyRule(`);
  if (fields.markFirst) lines.push('    markFirst: true,');
  if (fields.lead) lines.push(`    lead: ${quote(fields.lead)},`);
  if (fields.gap) lines.push(`    gap: ${quote(fields.gap)},`);
  lines.push(`    group: ${quote(fields.group)},`);
  lines.push(`    decimal: ${quote(fields.decimal)},`);
  if (fields.groupsFromFive) lines.push('    groupsFromFive: true,');
  if (fields.lakhs) lines.push('    lakhs: true,');
  if (fields.digits !== '0123456789') {
    lines.push(`    digits: ${quote(fields.digits)},`);
  }
  lines.push(
    `    marks: ${quote(
      Object.entries(marks).map(([code, mark]) => `${code}${mark}`).join('|'),
    )},`,
  );
  lines.push('  ),');
}
lines.push('};', '');
writeFileSync(join(picker, 'picker_money_table.g.dart'), lines.join('\n'));
console.log(`${tags.length} languages`);
